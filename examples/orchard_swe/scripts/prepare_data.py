#!/usr/bin/env python3
"""
Data preparation script for SWE-bench.

This script:
1. Downloads SWE-bench dataset from HuggingFace
2. Converts it to slime's JSONL format
3. Splits into train/val/test sets
"""

import argparse
import json
import random
from pathlib import Path

try:
    from datasets import load_dataset
except ImportError:
    raise ImportError(
        "datasets library not found. Please install it with:\n"
        "  pip install datasets"
    )


def convert_swebench_to_slime_format(instance: dict, dataset_name: str = "") -> dict:
    """
    Convert a SWE-bench instance to slime's format.

    An example of a SWE-bench datum is as follows:
    
    instance_id: (str) - A formatted instance identifier, usually as repo_owner__repo_name-PR-number.
    patch: (str) - The gold patch, the patch generated by the PR (minus test-related code), that resolved the issue.
    repo: (str) - The repository owner/name identifier from GitHub.
    base_commit: (str) - The commit hash of the repository representing the HEAD of the repository before the solution PR is applied.
    hints_text: (str) - Comments made on the issue prior to the creation of the solution PR’s first commit creation date.
    created_at: (str) - The creation date of the pull request.
    test_patch: (str) - A test-file patch that was contributed by the solution PR.
    problem_statement: (str) - The issue title and body.
    version: (str) - Installation version to use for running evaluation.
    environment_setup_commit: (str) - commit hash to use for environment setup and installation.
    FAIL_TO_PASS: (str) - A json list of strings that represent the set of tests resolved by the PR and tied to the issue resolution.
    PASS_TO_PASS: (str) - A json list of strings that represent tests that should pass before and after the PR application.

    Args:
        instance: SWE-bench instance dict

    Returns:
        Dict in slime's JSONL format
    """
    # Extract fields
    instance_id = instance.get("instance_id", "unknown")
    problem_statement = instance.get("problem_statement", "")
    patch = instance.get("patch", "")  # Ground truth patch (for reference)
    test_patch = instance.get("test_patch", "")
    repo = instance.get("repo", "")
    base_commit = instance.get("base_commit", "")
    version = instance.get("version", "")
    hints_text = instance.get("hints_text", "")
    created_at = instance.get("created_at", "")
    environment_setup_commit = instance.get("environment_setup_commit", "")
    fail_to_pass = instance.get("FAIL_TO_PASS", "")
    pass_to_pass = instance.get("PASS_TO_PASS", "")

    #problem_statement += "<possible_solution>\n\n" + patch + "\n\n</possible_solution>\n" # !!!!!!!!!!!! only for debugging

    # Build slime sample
    slime_sample = {
        # Main fields
        "problem_statement": problem_statement,
        "patch": patch,  # Ground truth (optional, for reference)

        # Metadata for environment setup and reward computation
        "metadata": {
            "dataset": dataset_name,
            "instance_id": instance_id,
            "repo": repo,
            "base_commit": base_commit,
            "version": version,
            "test_patch": test_patch,
            "hints_text": hints_text,
            "created_at": created_at,
            "environment_setup_commit": environment_setup_commit,
            "FAIL_TO_PASS": fail_to_pass,
            "PASS_TO_PASS": pass_to_pass,
        }
    }

    return slime_sample


