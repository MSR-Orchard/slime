def create_sample_subset(
    input_file: Path,
    output_file: Path,
    n_samples: int = 10
):
    """
    Create a small subset for testing.

    Args:
        input_file: Input JSONL file
        output_file: Output JSONL file
        n_samples: Number of samples to include
    """
    input_file = Path(input_file)
    output_file = Path(output_file)
    output_file.parent.mkdir(parents=True, exist_ok=True)

    print(f"Creating subset with {n_samples} samples")
    print(f"  Input: {input_file}")
    print(f"  Output: {output_file}")

    with open(input_file) as f_in, open(output_file, "w") as f_out:
        for idx, line in enumerate(f_in):
            if idx >= n_samples:
                break
            f_out.write(line)

    print(f"Subset created: {output_file}")


def main():
    parser = argparse.ArgumentParser(
        description="Prepare SWE-bench data for slime training"
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="data/swebench",
        help="Output directory for JSONL files",
    )
    parser.add_argument(
        "--dataset",
        type=str,
        default="princeton-nlp/SWE-bench_Verified",
        help="HuggingFace dataset name",
    )
    parser.add_argument(
        "--subset",
        type=str,
        default=None,
        help="Optional dataset subset",
    )
    parser.add_argument(
        "--train-size",
        type=int,
        default=400,
        help="Number of instances for training set (when manually splitting)",
    )
    parser.add_argument(
        "--dev-size",
        type=int,
        default=50,
        help="Number of instances for dev set (when manually splitting)",
    )
    parser.add_argument(
        "--test-size",
        type=int,
        default=50,
        help="Number of instances for test set (when manually splitting)",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for shuffling before splitting (ensures reproducibility)",
    )

    args = parser.parse_args()

    if "SWE-bench_Verified" in args.dataset:
        # Prepare main dataset
        prepare_swebench_data(
            output_dir=args.output_dir,
            dataset_name=args.dataset,
            subset=args.subset,
            train_size=args.train_size,
            dev_size=args.dev_size,
            test_size=args.test_size,
            seed=args.seed,
        )
        # Always create small (10%) versions of each split
        print("\n" + "=" * 60)
        print("Creating small (10%) subsets...")
        print("=" * 60)

        output_dir = Path(args.output_dir)

        for split_name, full_size in [("train", args.train_size), ("dev", args.dev_size), ("test", args.test_size)]:
            split_file = output_dir / f"swebench_{split_name}.jsonl"
            if split_file.exists():
                small_size = max(1, full_size // 10)
                create_sample_subset(
                    input_file=split_file,
                    output_file=output_dir / f"swebench_{split_name}_small.jsonl",
                    n_samples=small_size,
                )
    elif "SWE-rebench" in args.dataset:
        prepare_swerebench_data(
            output_dir=args.output_dir,
            dataset_name=args.dataset,
            subset=args.subset,
            seed=args.seed,
        )
    elif "Scale-SWE" in args.dataset:
        prepare_scaleswe_data(
            output_dir=args.output_dir,
            dataset_name=args.dataset,
            subset=args.subset,
            seed=args.seed,
        )
    else:
        raise ValueError(f"Unsupported dataset: {args.dataset}")


if __name__ == "__main__":
    main()
